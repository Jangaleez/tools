# ---------------------------------------------------------------- terminal helpers

class C:
    ok = "\033[32m"
    bad = "\033[31m"
    warn = "\033[33m"
    bold = "\033[1m"
    dim = "\033[2m"
    end = "\033[0m"


def say(text=""):
    print(text, flush=True)


def ok(text):
    say(f"  {C.ok}✔{C.end} {text}")


def warn(text):
    say(f"  {C.warn}▲{C.end} {text}")


def fail(text):
    say(f"  {C.bad}✖ {text}{C.end}")


def heading(text):
    say(f"\n{C.bold}{text}{C.end}")


def clear_screen():
    """Clears the screen AND the scrollback, so phrases can't be scrolled back to."""
    sys.stdout.write("\033[3J\033[H\033[2J")
    sys.stdout.flush()
    os.system("clear 2>/dev/null")
    sys.stdout.write("\033[3J")
    sys.stdout.flush()


def pause(text="Press Enter to continue..."):
    input(f"\n{text}")


def ask_yes(question, default=False):
    hint = "[Y/n]" if default else "[y/N]"
    while True:
        a = input(f"{question} {hint} ").strip().lower()
        if not a:
            return default
        if a in ("y", "yes"):
            return True
        if a in ("n", "no"):
            return False


def ask_choice(question, options):
    """options: list of (key, label). Returns the chosen key."""
    say(question)
    for i, (_, label) in enumerate(options, 1):
        say(f"   {i}) {label}")
    while True:
        a = input("Choose a number: ").strip()
        if a.isdigit() and 1 <= int(a) <= len(options):
            return options[int(a) - 1][0]


class Stop(Exception):
    """A safety check failed: stop without generating anything."""


# ---------------------------------------------------------------- environment checks

def in_tails():
    return Path("/etc/amnesia/version").exists()


def active_network():
    """Names of network interfaces that are up (anything except loopback)."""
    active = []
    for iface in sorted(Path("/sys/class/net").glob("*")):
        if iface.name == "lo":
            continue
        state = (iface / "operstate").read_text().strip() if (iface / "operstate").exists() else "unknown"
        carrier = ""
        try:
            carrier = (iface / "carrier").read_text().strip()
        except OSError:
            pass
        if state == "up" or carrier == "1":
            active.append(iface.name)
    return active


def has_default_route():
    try:
        for line in Path("/proc/net/route").read_text().splitlines()[1:]:
            parts = line.split()
            if len(parts) > 2 and parts[1] == "00000000":
                return True
    except OSError:
        pass
    try:
        for line in Path("/proc/net/ipv6_route").read_text().splitlines():
            parts = line.split()
            if parts and parts[0] == "0" * 32 and parts[1] == "00" and parts[-1] != "lo":
                return True
    except OSError:
        pass
    return False


def can_reach_internet():
    for host in (("1.1.1.1", 443), ("9.9.9.9", 443)):
        try:
            with socket.create_connection(host, timeout=2):
                return True
        except OSError:
            pass
    return False


def try_switch_network_off():
    """Best effort: NetworkManager off, all radios off, rfkill block. Works without root on most desktops."""
    cmds = [["nmcli", "networking", "off"], ["nmcli", "radio", "all", "off"], ["rfkill", "block", "all"]]
    for cmd in cmds:
        if shutil.which(cmd[0]):
            subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=15)
    time.sleep(3)


def check_offline():
    heading("1. Network")
    if in_tails():
        ok("Running on Tails (everything is wiped from memory when you shut down).")
    else:
        warn("This is NOT Tails. For real keys, use a Tails USB stick started in Offline Mode.")
    for attempt in range(2):
        nets, route = active_network(), has_default_route()
        online = can_reach_internet()
        if not nets and not route and not online:
            ok("No network connection. Wi-Fi, Ethernet and Bluetooth are off.")
            return
        problem = []
        if nets:
            problem.append("active network: " + ", ".join(nets))
        if route:
            problem.append("a route to the internet exists")
        if online:
            problem.append("the internet is reachable")
        warn("Still online (" + "; ".join(problem) + ").")
        if attempt == 0:
            say("  Trying to switch all networking off...")
            try_switch_network_off()
    raise Stop("The computer is still connected. Restart Tails and turn on Offline Mode on the Welcome "
               "Screen (Additional Settings, or Alt+A), or unplug the network cable and turn Wi-Fi off.")


def check_processes():
    heading("2. Screen sharing and remote access")
    found = set()
    for p in Path("/proc").glob("[0-9]*"):
        try:
            name = (p / "comm").read_text().strip()
        except OSError:
            continue
        if name in RISKY_PROGRAMS:
            found.add(name)
    if os.environ.get("SSH_CONNECTION") or os.environ.get("SSH_TTY"):
        raise Stop("This is running over SSH. Run it directly on the offline computer.")
    if found:
        warn("These programs could record or share the screen: " + ", ".join(sorted(found)))
        if not ask_yes("  Close them first. Continue anyway?"):
            raise Stop("Stopped so you can close those programs.")
    else:
        ok("No screen-sharing, remote-desktop or recording programs running.")


