def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def check_manifest():
    heading("3. Bundle")
    manifest = HERE / "MANIFEST.sha256"
    if not manifest.exists():
        raise Stop("MANIFEST.sha256 is missing. Make the bundle with prepare_bundle.py.")
    text = manifest.read_text()
    bad = []
    for line in text.splitlines():
        if not line.strip():
            continue
        digest, name = line.split(None, 1)
        name = name.lstrip("*")
        f = HERE / name
        if not f.is_file() or sha256_file(f) != digest:
            bad.append(name)
    listed = {l.split(None, 1)[1].lstrip("*") for l in text.splitlines() if l.strip()}
    for f in HERE.rglob("*"):
        rel = f.relative_to(HERE).as_posix()
        if f.is_file() and rel not in listed and rel != "MANIFEST.sha256" and not rel.startswith("__pycache__"):
            bad.append(f"{rel} (not in the manifest)")
    if bad:
        raise Stop("These bundle files were changed or added after it was made: " + ", ".join(bad[:8]))
    code = hashlib.sha256(text.encode()).hexdigest()[:16].upper()
    ok(f"All {len(listed)} files match the manifest.")
    say(f"     Bundle code: {C.bold}{' '.join(code[i:i + 4] for i in range(0, 16, 4))}{C.end}"
        f"  (should match what prepare_bundle.py printed)")


def check_bitcoin_release():
    d = HERE / "bitcoin"
    tarball, sums, sig = d / BTC_TARBALL, d / "SHA256SUMS", d / "SHA256SUMS.asc"
    for f in (tarball, sums, sig):
        if not f.exists():
            raise Stop(f"Missing {f.relative_to(HERE)}")
    digest = sha256_file(tarball)
    if digest != BTC_SHA256:
        raise Stop("The Bitcoin Core download does not match the hash 13 Bitcoin Core builders signed.")
    if f"{digest}  {BTC_TARBALL}" not in sums.read_text():
        raise Stop("Bitcoin Core's SHA256SUMS file doesn't list this download.")
    ok(f"Bitcoin Core {BTC_VERSION} download matches the builders' signed hash.")
    if not shutil.which("gpg"):
        warn("gpg isn't available, so the signature file couldn't be checked (the pinned hash above still was).")
        return
    home = tempfile.mkdtemp(prefix="ck-gpg-", dir=ram_dir())
    try:
        env = {**os.environ, "GNUPGHOME": home}
        for key in sorted((d / "builder-keys").glob("*.gpg")):
            subprocess.run(["gpg", "--batch", "--quiet", "--import", str(key)], env=env,
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        r = subprocess.run(["gpg", "--batch", "--status-fd", "1", "--verify", str(sig), str(sums)], env=env,
                           capture_output=True, text=True)
        signed = {line.split()[-1] for line in r.stdout.splitlines() if line.startswith("[GNUPG:] VALIDSIG")}
        good = sorted(name for name, fpr in BUILDERS.items() if fpr in signed)
    finally:
        shutil.rmtree(home, ignore_errors=True)
    if len(good) < MIN_SIGS:
        raise Stop(f"Only {len(good)} trusted Bitcoin Core builder signature(s) found; at least {MIN_SIGS} needed.")
    ok(f"SHA256SUMS signed by {len(good)} Bitcoin Core builders: {', '.join(good)}.")


def check_solana_release():
    d = HERE / "solana"
    info_file, tarball = d / "release.json", d / SOL_TARBALL
    if not info_file.exists() or not tarball.exists():
        raise Stop("The Solana CLI download is missing from the bundle.")
    info = json.loads(info_file.read_text())
    if sha256_file(tarball) != info.get("sha256"):
        raise Stop("The Solana CLI download doesn't match the hash GitHub recorded for the release.")
    ok(f"Solana CLI {info.get('tag', '?')} matches GitHub's recorded hash for the official release.")


# ---------------------------------------------------------------- unpacking into memory

_RAM = None


def ram_dir():
    """A RAM-backed folder where programs are allowed to run (Tails keeps /tmp and home in RAM)."""
    global _RAM
    if _RAM:
        return _RAM
    candidates = [os.environ.get("XDG_RUNTIME_DIR"), "/dev/shm", tempfile.gettempdir(), str(Path.home())]
    for c in candidates:
        if not c or not os.path.isdir(c) or not os.access(c, os.W_OK):
            continue
        try:
            test = tempfile.mkdtemp(prefix="ck-", dir=c)
            script = Path(test) / "t.sh"
            script.write_text("#!/bin/sh\nexit 0\n")
            script.chmod(0o700)
            runs = subprocess.run([str(script)]).returncode == 0
            shutil.rmtree(test, ignore_errors=True)
            if runs:
                _RAM = c
                return c
        except OSError:
            continue
    raise Stop("Couldn't find a temporary folder that allows running programs.")


def safe_extract(tar, dest, members):
    for m in members:
        if not m.isfile() or m.name.startswith("/") or ".." in Path(m.name).parts:
            raise Stop(f"Unexpected file in download: {m.name}")
    try:
        tar.extractall(dest, members=members, filter="data")
    except TypeError:  # Python without extraction filters (members were checked above)
        tar.extractall(dest, members=members)


class Workspace:
    def __init__(self):
        self.dir = Path(tempfile.mkdtemp(prefix="coldkeys-", dir=ram_dir()))
        os.chmod(self.dir, 0o700)
        self.bitcoind = self.bitcoin_cli = self.keygen = None

    def unpack(self):
        heading("4. Unpacking the official tools into memory")
        with tarfile.open(HERE / "bitcoin" / BTC_TARBALL) as t:
            members = [m for m in t.getmembers() if m.name.endswith(("/bin/bitcoind", "/bin/bitcoin-cli"))]
            safe_extract(t, self.dir / "btc", members)
        for p in (self.dir / "btc").rglob("*"):
            if p.name == "bitcoind":
                self.bitcoind = p
            elif p.name == "bitcoin-cli":
                self.bitcoin_cli = p
        with tarfile.open(HERE / "solana" / SOL_TARBALL) as t:
            members = [m for m in t.getmembers() if m.name.endswith("/bin/solana-keygen")]
            safe_extract(t, self.dir / "sol", members)
        self.keygen = next((self.dir / "sol").rglob("solana-keygen"), None)
        for p in (self.bitcoind, self.bitcoin_cli, self.keygen):
            if not p:
                raise Stop("A program is missing from the official downloads.")
            p.chmod(0o700)
        ok("Bitcoin Core and Solana CLI unpacked.")

        whl_dir = self.dir / "py"
        wheels = sorted((HERE / "python").glob("*.whl"))
        if not wheels:
            raise Stop("The Python libraries are missing from the bundle.")
        tag = f"cp{sys.version_info.major}{sys.version_info.minor}"
        compiled = [w.name for w in wheels if "-cp3" in w.name and "abi3" not in w.name]
        if compiled and not all(f"-{tag}-" in w for w in compiled):
            raise Stop(f"The bundle was made for a different Python version than this computer's ({tag}). "
                       f"Re-run prepare_bundle.py with --python-version {sys.version_info.major}."
                       f"{sys.version_info.minor}")
        for w in wheels:
            with zipfile.ZipFile(w) as z:
                z.extractall(whl_dir)
        sys.path.insert(0, str(whl_dir))
        ok(f"{len(wheels)} Python libraries unpacked (BIP39 reference + Ethereum Foundation's eth-account).")

    def cleanup(self):
        shutil.rmtree(self.dir, ignore_errors=True)


# ---------------------------------------------------------------- Bitcoin (via Bitcoin Core)

B58 = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz"
SECP256K1_N = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141


def b58check(payload):
    data = payload + hashlib.sha256(hashlib.sha256(payload).digest()).digest()[:4]
    n = int.from_bytes(data, "big")
    out = ""
    while n:
        n, r = divmod(n, 58)
        out = B58[r] + out
    return "1" * (len(data) - len(data.lstrip(b"\0"))) + out


def master_xprv(seed):
    """BIP32 master key. The elliptic-curve work (child keys, addresses) is all done by Bitcoin Core."""
    i = hmac.new(b"Bitcoin seed", seed, hashlib.sha512).digest()
    k, chain = i[:32], i[32:]
    if not 0 < int.from_bytes(k, "big") < SECP256K1_N:
        raise Stop("Invalid master key (astronomically unlikely) - generate again.")
    return b58check(bytes.fromhex("0488ADE4") + b"\0" * 9 + chain + b"\0" + k)


class CoreNode:
    """A private, offline Bitcoin Core node used only as a calculator for addresses."""

    def __init__(self, ws):
        self.ws = ws
        self.datadir = ws.dir / "btc-data"
        self.datadir.mkdir()
        with socket.socket() as s:
            s.bind(("127.0.0.1", 0))
            self.port = s.getsockname()[1]
        self.proc = None

    def args(self):
        return [f"-datadir={self.datadir}", f"-rpcport={self.port}", "-chain=main"]

    def start(self):
        self.proc = subprocess.Popen(
            [str(self.ws.bitcoind), *self.args(), "-server=1", "-listen=0", "-connect=0", "-dnsseed=0",
             "-fixedseeds=0", "-networkactive=0", "-discover=0", "-disablewallet=1", "-nodebuglogfile",
             "-rpcbind=127.0.0.1", "-rpcallowip=127.0.0.1", "-printtoconsole=0"],
            stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)
        for _ in range(120):
            if self.proc.poll() is not None:
                raise Stop("Bitcoin Core didn't start: " + self.proc.stderr.read().decode(errors="replace")[-300:])
            r = subprocess.run([str(self.ws.bitcoin_cli), *self.args(), "getnetworkinfo"], capture_output=True, text=True)
            if r.returncode == 0:
                info = json.loads(r.stdout)
                if info.get("networkactive") or info.get("connections"):
                    raise Stop("Bitcoin Core's networking is on - refusing to continue.")
                return
            time.sleep(0.5)
        raise Stop("Bitcoin Core didn't start in time.")

    def call(self, method, *args):
        """Arguments go through stdin (-stdin) so keys never appear in the process list."""
        r = subprocess.run([str(self.ws.bitcoin_cli), *self.args(), "-stdin", method],
                           input="".join(f"{a}\n" for a in args), capture_output=True, text=True)
        if r.returncode != 0:
            raise Stop(f"Bitcoin Core {method} failed: {r.stderr.strip()[:200]}")
        return json.loads(r.stdout)

    def addresses(self, seed, purpose, count=3):
        xprv = master_xprv(seed)
        wrap = {84: "wpkh", 86: "tr"}[purpose]
        desc = f"{wrap}({xprv}/{purpose}h/0h/0h/0/*)"
        info = self.call("getdescriptorinfo", desc)
        full = f"{desc}#{info['checksum']}"
        addrs = self.call("deriveaddresses", full, json.dumps([0, count - 1]))
        return addrs, info.get("descriptor")

    def stop(self):
        if self.proc and self.proc.poll() is None:
            subprocess.run([str(self.ws.bitcoin_cli), *self.args(), "stop"], capture_output=True)
            try:
                self.proc.wait(timeout=30)
            except subprocess.TimeoutExpired:
                self.proc.kill()
        shutil.rmtree(self.datadir, ignore_errors=True)


# ---------------------------------------------------------------- Solana (via solana-keygen)

def run_in_pty(cmd, answers, timeout=60):
    """Run a program in a pseudo-terminal, answering its hidden prompts. Secrets never touch argv."""
    import pty  # Linux-only, so imported here (the bundle maker imports this file on Windows)
    pid, fd = pty.fork()
    if pid == 0:  # child
        os.environ["LC_ALL"] = "C"
        os.execv(cmd[0], cmd)
    out, pending, deadline = b"", list(answers), time.time() + timeout
    try:
        while time.time() < deadline:
            r, _, _ = select.select([fd], [], [], 0.5)
            if r:
                try:
                    chunk = os.read(fd, 4096)
                except OSError:
                    break
                if not chunk:
                    break
                out += chunk
                while pending and pending[0][0].lower().encode() in out.split(b"\n")[-1].lower():
                    os.write(fd, pending.pop(0)[1].encode() + b"\n")
                    out += b"\n"
            elif os.waitpid(pid, os.WNOHANG)[0]:
                break
    finally:
        try:
            os.close(fd)
        except OSError:
            pass
        try:
            _, status = os.waitpid(pid, 0)
        except ChildProcessError:
            status = 0
    return os.waitstatus_to_exitcode(status), out.decode(errors="replace").replace("\r", "")


def sol_generate(ws, words, passphrase):
    cmd = [str(ws.keygen), "new", "--no-outfile", "--word-count", str(words), "--derivation-path"]
    answers = []
    if passphrase:
        answers = [("passphrase", passphrase), ("again", passphrase)]
    else:
        cmd.append("--no-bip39-passphrase")
    code, out = run_in_pty(cmd, answers)
    if code != 0 or "pubkey:" not in out:
        raise Stop("solana-keygen failed: " + out.strip()[-200:])
    pubkey = out.split("pubkey:")[1].split()[0]
    lines = [l.strip() for l in out.splitlines()]
    idx = next(i for i, l in enumerate(lines) if l.startswith("Save this seed phrase"))
    phrase = lines[idx + 1]
    return phrase, pubkey


def sol_address(ws, phrase, passphrase, account=0):
    code, out = run_in_pty([str(ws.keygen), "pubkey", f"prompt://?key={account}/0"],
                           [("seed phrase", phrase), ("passphrase", passphrase), ("again", passphrase)])
    words = out.strip().split()
    if code != 0 or not words:
        raise Stop("solana-keygen pubkey failed.")
    return words[-1]


